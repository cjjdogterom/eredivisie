export const championsWithWinner = champions.filter((c) => c.club !== null);

export function getClubStats() {
  const map = new Map<string, { total: number; eredivisie: number; seasons: string[] }>();

  for (const c of championsWithWinner) {
    const existing = map.get(c.club!) ?? { total: 0, eredivisie: 0, seasons: [] };
    existing.total += 1;
    if (c.era === 'eredivisie') existing.eredivisie += 1;
    existing.seasons.push(String(c.year));
    map.set(c.club!, existing);
  }

  return Array.from(map.entries())
    .map(([club, data]) => ({
      club,
      totalTitles: data.total,
      eredivisieTitles: data.eredivisie,
      seasons: data.seasons,
      firstTitle: data.seasons[0],
      lastTitle: data.seasons[data.seasons.length - 1],
    }))
    .sort((a, b) => b.totalTitles - a.totalTitles);
}

export function getUniqueClubs(): string[] {
  return [...new Set(championsWithWinner.map((c) => c.club!))].sort();
}
